"""
FraudLens — Interactive College Demonstration Router
Endpoint group: /api/demo
Provides scripted demo scenarios to demonstrate the end-to-end DBMS workflow
for university professors and examiners:
1. Create a normal transaction (under threshold) -> No alert generated
2. Create a high-value transaction (₹125,000 > ₹50,000 threshold) -> Stored procedure flags and triggers alert
3. Inspect generated alert in FRAUD_ALERTS
4. Open an investigation case docket linked to the alert
5. Assign active investigator via SP_ASSIGN_INVESTIGATOR
6. Update investigation status to CLOSED with outcome CONFIRMED_FRAUD via SP_UPDATE_INVESTIGATION_STATUS
7. Inspect the resulting audit record generated by TRG_INVESTIGATION_STATUS_AUDIT in INVESTIGATION_AUDIT
8. Verify refreshed metrics on the Executive Dashboard
"""

from typing import Any, Dict
from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel

from app.backend.repositories import get_repo, is_live_mode
from app.backend.schemas.common import ApiResponse

router = APIRouter(prefix="/demo", tags=["Demonstration Mode"])


class DemoRunResult(BaseModel):
    step1_normal_tx: Dict[str, Any]
    step2_high_amount_tx: Dict[str, Any]
    step3_alert_generated: Dict[str, Any]
    step4_case_opened: Dict[str, Any]
    step5_investigator_assigned: Dict[str, Any]
    step6_case_closed: Dict[str, Any]
    step7_audit_logged: Dict[str, Any]
    step8_dashboard_kpis: Dict[str, Any]


@router.post("/run-scenario", response_model=ApiResponse[DemoRunResult])
def run_full_demo_scenario():
    """
    Executes the complete 8-step live demonstration lifecycle against the active database
    in a single atomic flow, returning verifiable evidence at each phase.
    """
    repo = get_repo()

    try:
        # Step 1: Normal transaction (₹15,000 - under ₹50,000 threshold)
        tx_normal = repo.create_transaction(
            account_id=2001,
            transaction_type="PAYMENT",
            amount=15000.0,
            channel="UPI",
            counterparty_account="ACT-DEMO-NORM-01",
            description="Regular grocery payment",
        )
        step1_info = {
            "transaction_id": tx_normal.get("transaction_id"),
            "amount": f"₹{tx_normal.get('amount', 0):,.2f}",
            "type": tx_normal.get("transaction_type"),
            "status": tx_normal.get("status"),
            "alert_generated": tx_normal.get("alert_generated", False),
            "note": "Amount ₹15,000 < ₹50,000 threshold. No alert triggered.",
        }

        # Step 2: High-amount transaction (₹1,25,000 - exceeds ₹50,000 threshold)
        tx_high = repo.create_transaction(
            account_id=2002,
            transaction_type="TRANSFER",
            amount=125000.0,
            channel="NET_BANKING",
            counterparty_account="ACT-DEMO-HIGH-99",
            description="High value interbank transfer",
        )
        step2_info = {
            "transaction_id": tx_high.get("transaction_id"),
            "amount": f"₹{tx_high.get('amount', 0):,.2f}",
            "type": tx_high.get("transaction_type"),
            "status": tx_high.get("status"),
            "alert_generated": tx_high.get("alert_generated", True),
            "rule_triggered": tx_high.get("rule_triggered") or "RULE_HIGH_AMOUNT (SP_EVALUATE_AND_ALERT_TRANSACTION)",
        }

        # Step 3: Verify the newly generated alert
        alerts_items, _ = repo.get_alerts(page=1, page_size=5)
        new_alert = next((a for a in alerts_items if a.get("transaction_id") == tx_high.get("transaction_id")), None)
        if not new_alert and alerts_items:
            new_alert = alerts_items[0]

        step3_info = {
            "alert_id": new_alert.get("alert_id") if new_alert else None,
            "rule_name": new_alert.get("rule_triggered") if new_alert else "RULE_HIGH_AMOUNT",
            "severity": new_alert.get("severity") if new_alert else "CRITICAL",
            "status": new_alert.get("status") if new_alert else "PENDING",
            "description": "High transaction amount exceeded ₹50,000 threshold.",
        }

        # Step 4: Open investigation docket for this alert
        alert_id_to_use = new_alert.get("alert_id") if new_alert else 7005
        case = repo.create_investigation(
            alert_id=alert_id_to_use,
            investigator_id=None,
            notes="Demo Case: Automated triage initiated for high-amount NEFT anomaly.",
        )
        inv_id = case.get("investigation_id")
        step4_info = {
            "investigation_id": inv_id,
            "alert_id": case.get("alert_id"),
            "status": case.get("status"),
            "created_at": str(case.get("start_date")),
        }

        # Step 5: Assign investigator (Dr. Rajesh Sharma, ID 301) via SP_ASSIGN_INVESTIGATOR
        repo.assign_investigator(
            investigation_id=inv_id,
            investigator_id=301,
        )
        assigned = repo.get_investigation_by_id(inv_id) or case
        step5_info = {
            "investigation_id": assigned.get("investigation_id"),
            "investigator_id": assigned.get("investigator_id"),
            "investigator_name": assigned.get("investigator_name"),
            "status": assigned.get("status"),
            "note": "Assigned using Oracle PL/SQL procedure SP_ASSIGN_INVESTIGATOR",
        }

        # Step 6: Close investigation with outcome CONFIRMED_FRAUD via SP_UPDATE_INVESTIGATION_STATUS
        repo.update_investigation_status(
            investigation_id=inv_id,
            new_status="CLOSED",
            outcome="CONFIRMED_FRAUD",
            notes="Live Demo Conclusion: Customer confirmed unauthorized fund transfer attempt. Flagged and locked.",
        )
        closed = repo.get_investigation_by_id(inv_id) or assigned
        step6_info = {
            "investigation_id": closed.get("investigation_id"),
            "status": closed.get("status"),
            "outcome": closed.get("outcome"),
            "closed_at": str(closed.get("end_date")),
            "note": "Procedure SP_UPDATE_INVESTIGATION_STATUS executed. Row-level trigger fired.",
        }

        # Step 7: Inspect audit trail generated by TRG_INVESTIGATION_STATUS_AUDIT
        audit_items, _ = repo.get_audit_logs(page=1, page_size=5, source_table="INVESTIGATION_AUDIT")
        latest_audit = audit_items[0] if audit_items else {}
        step7_info = {
            "audit_id": latest_audit.get("audit_id", 999),
            "table_name": latest_audit.get("source_table", "INVESTIGATION_AUDIT"),
            "operation": latest_audit.get("action_type", "UPDATE"),
            "record_id": latest_audit.get("record_id", inv_id),
            "old_status": latest_audit.get("old_status", "OPEN"),
            "new_status": latest_audit.get("new_status", "CLOSED"),
            "db_user": latest_audit.get("changed_by", "FRAUDLENS_USER"),
            "note": "Audit entry automatically written by database trigger TRG_INVESTIGATION_STATUS_AUDIT",
        }

        # Step 8: Refreshed executive dashboard metrics
        kpis = repo.get_dashboard_summary()
        step8_info = {
            "total_transactions": kpis.get("total_transactions", 0),
            "total_volume_inr": f"₹{kpis.get('total_volume_inr', 0):,.2f}",
            "flagged_transactions": kpis.get("flagged_transactions", 0),
            "open_investigations": kpis.get("open_investigations", 0),
            "closed_investigations": kpis.get("closed_investigations", 0),
            "confirmed_fraud_cases": kpis.get("confirmed_fraud_cases", 0),
        }

        result = DemoRunResult(
            step1_normal_tx=step1_info,
            step2_high_amount_tx=step2_info,
            step3_alert_generated=step3_info,
            step4_case_opened=step4_info,
            step5_investigator_assigned=step5_info,
            step6_case_closed=step6_info,
            step7_audit_logged=step7_info,
            step8_dashboard_kpis=step8_info,
        )

        return ApiResponse(
            success=True,
            data=result,
            message="Live College Demonstration Scenario executed successfully with full database audit logging",
            is_live_oracle=is_live_mode(),
        )

    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Demonstration workflow failed: {str(e)}",
        )
