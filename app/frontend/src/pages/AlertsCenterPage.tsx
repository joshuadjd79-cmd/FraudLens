import React, { useState, useEffect } from 'react';
import {
  ShieldAlert,
  Search,
  Filter,
  Briefcase,
  ChevronLeft,
  ChevronRight,
  Eye,
  AlertTriangle,
  ArrowRight,
  Clock,
  CheckCircle2,
} from 'lucide-react';
import { Alert, SeverityLevel, AlertStatus } from '../types';
import { api } from '../api/client';
import { SeverityBadge, StatusBadge } from '../components/common/Badge';
import { Modal } from '../components/common/Modal';
import { NavTab } from '../components/common/Sidebar';

interface AlertsCenterPageProps {
  onNavigateToInvestigations: () => void;
  onRefreshTrigger?: () => void;
}

export const AlertsCenterPage: React.FC<AlertsCenterPageProps> = ({
  onNavigateToInvestigations,
  onRefreshTrigger,
}) => {
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [totalCount, setTotalCount] = useState<number>(0);
  const [page, setPage] = useState<number>(1);
  const [pageSize] = useState<number>(10);
  const [totalPages, setTotalPages] = useState<number>(1);
  const [isLoading, setIsLoading] = useState<boolean>(true);

  // Filters
  const [severityFilter, setSeverityFilter] = useState<string>('');
  const [statusFilter, setStatusFilter] = useState<string>('');
  const [search, setSearch] = useState<string>('');

  // Selected Alert for Details Modal
  const [selectedAlert, setSelectedAlert] = useState<Alert | null>(null);

  // Escalation / Investigation Creation State
  const [isEscalating, setIsEscalating] = useState<boolean>(false);
  const [escalateError, setEscalateError] = useState<string | null>(null);
  const [escalateSuccess, setEscalateSuccess] = useState<string | null>(null);

  const loadAlerts = async () => {
    try {
      setIsLoading(true);
      const res = await api.getAlerts({
        page,
        page_size: pageSize,
        severity: severityFilter || undefined,
        status: statusFilter || undefined,
        search: search || undefined,
      });
      setAlerts(res.items);
      setTotalCount(res.total);
      setTotalPages(res.total_pages);
    } catch (err: any) {
      console.error('Failed to load alerts:', err);
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    loadAlerts();
  }, [page, severityFilter, statusFilter]);

  const handleSearchSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setPage(1);
    loadAlerts();
  };

  const handleEscalateToInvestigation = async (alert: Alert) => {
    setEscalateError(null);
    setEscalateSuccess(null);
    try {
      setIsEscalating(true);
      const newCase = await api.createInvestigation({
        alert_id: alert.alert_id,
        notes: `Escalated from Alerts Center for surveillance anomaly on transaction #${alert.transaction_id}`,
      });
      setEscalateSuccess(`Investigation Case #${newCase.investigation_id} opened successfully!`);
      loadAlerts();
      if (onRefreshTrigger) onRefreshTrigger();
    } catch (err: any) {
      setEscalateError(err.message || 'Escalation failed');
    } finally {
      setIsEscalating(false);
    }
  };

  const formatINR = (val: number) => {
    return new Intl.NumberFormat('en-IN', {
      style: 'currency',
      currency: 'INR',
      maximumFractionDigits: 2,
    }).format(val);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-bold text-white tracking-tight">Fraud Alerts Center</h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Automated alerts generated by Oracle PL/SQL rules engine (SP_EVALUATE_AND_ALERT_TRANSACTION)
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={onNavigateToInvestigations}
            className="flex items-center gap-2 px-3.5 py-2 rounded-xl bg-slate-900 hover:bg-slate-800 border border-slate-700 text-xs font-medium text-slate-200 transition-colors"
          >
            <Briefcase className="w-3.5 h-3.5 text-cyan-400" />
            <span>Open Case Dockets</span>
          </button>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="p-4 rounded-xl bg-slate-900 border border-slate-800 flex flex-col md:flex-row gap-3 items-stretch md:items-center justify-between">
        <form onSubmit={handleSearchSubmit} className="relative flex-1">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Search by Alert ID, Rule Name, or Transaction ID..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full pl-10 pr-4 py-2 rounded-lg bg-slate-950 border border-slate-800 text-xs text-white placeholder-slate-500 focus:outline-none focus:border-cyan-500 transition-colors"
          />
        </form>

        <div className="flex items-center gap-2">
          {/* Severity Filter */}
          <select
            value={severityFilter}
            onChange={(e) => {
              setSeverityFilter(e.target.value);
              setPage(1);
            }}
            className="px-3 py-2 rounded-lg bg-slate-950 border border-slate-800 text-xs text-slate-300 focus:outline-none focus:border-cyan-500"
          >
            <option value="">All Severities</option>
            <option value="CRITICAL">Critical</option>
            <option value="HIGH">High</option>
            <option value="MEDIUM">Medium</option>
            <option value="LOW">Low</option>
          </select>

          {/* Status Filter */}
          <select
            value={statusFilter}
            onChange={(e) => {
              setStatusFilter(e.target.value);
              setPage(1);
            }}
            className="px-3 py-2 rounded-lg bg-slate-950 border border-slate-800 text-xs text-slate-300 focus:outline-none focus:border-cyan-500"
          >
            <option value="">All Statuses</option>
            <option value="PENDING">Pending Triage</option>
            <option value="ESCALATED">Escalated</option>
            <option value="RESOLVED">Resolved</option>
          </select>
        </div>
      </div>

      {/* Alerts Table */}
      <div className="rounded-xl bg-slate-900 border border-slate-800 overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-slate-800 bg-slate-950/50 text-slate-400 font-mono">
                <th className="py-3 px-4 font-semibold">Alert ID</th>
                <th className="py-3 px-4 font-semibold">Triggered Surveillance Rule</th>
                <th className="py-3 px-4 font-semibold">Severity</th>
                <th className="py-3 px-4 font-semibold">Transaction Info</th>
                <th className="py-3 px-4 font-semibold">Amount</th>
                <th className="py-3 px-4 font-semibold">Status</th>
                <th className="py-3 px-4 font-semibold">Detection Date</th>
                <th className="py-3 px-4 font-semibold text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 font-sans">
              {isLoading ? (
                <tr>
                  <td colSpan={8} className="py-12 text-center text-slate-400 font-mono text-xs">
                    Querying Oracle FRAUD_ALERTS table...
                  </td>
                </tr>
              ) : alerts.length === 0 ? (
                <tr>
                  <td colSpan={8} className="py-12 text-center text-slate-400">
                    No alerts found matching current filters.
                  </td>
                </tr>
              ) : (
                alerts.map((a) => (
                  <tr key={a.alert_id} className="hover:bg-slate-800/40 transition-colors">
                    <td className="py-3 px-4 font-mono font-bold text-cyan-400">#{a.alert_id}</td>
                    <td className="py-3 px-4 max-w-xs">
                      <div className="font-medium text-slate-200 truncate">{a.rule_triggered}</div>
                      <div className="text-[10px] font-mono text-slate-500">Type: {a.alert_type}</div>
                    </td>
                    <td className="py-3 px-4">
                      <SeverityBadge severity={a.severity} />
                    </td>
                    <td className="py-3 px-4">
                      <div className="font-medium text-slate-200">
                        {a.customer_name || 'Customer'}
                      </div>
                      <div className="text-[10px] font-mono text-slate-400">
                        Tx #{a.transaction_id} ({a.channel || 'N/A'})
                      </div>
                    </td>
                    <td className="py-3 px-4 font-mono font-bold text-white text-[13px]">
                      {a.amount ? formatINR(a.amount) : 'N/A'}
                    </td>
                    <td className="py-3 px-4">
                      <StatusBadge status={a.status} />
                    </td>
                    <td className="py-3 px-4 font-mono text-[11px] text-slate-400 whitespace-nowrap">
                      {a.alert_date}
                    </td>
                    <td className="py-3 px-4 text-right">
                      <div className="flex items-center justify-end gap-1.5">
                        <button
                          onClick={() => {
                            setEscalateError(null);
                            setEscalateSuccess(null);
                            setSelectedAlert(a);
                          }}
                          className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white transition-colors"
                          title="View Alert Dossier"
                        >
                          <Eye className="w-3.5 h-3.5" />
                        </button>

                        {!a.has_investigation && a.status !== 'RESOLVED' && (
                          <button
                            onClick={() => handleEscalateToInvestigation(a)}
                            disabled={isEscalating}
                            className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-cyan-500/10 hover:bg-cyan-500/20 text-cyan-400 border border-cyan-500/30 text-[11px] font-medium transition-colors"
                            title="Open Investigation Docket"
                          >
                            <Briefcase className="w-3 h-3" />
                            <span>Escalate</span>
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination */}
        <div className="p-4 border-t border-slate-800 flex items-center justify-between text-xs text-slate-400">
          <div>
            Page <span className="font-bold text-white font-mono">{page}</span> of{' '}
            <span className="font-bold text-white font-mono">{totalPages}</span> (Total{' '}
            <span className="font-bold text-white font-mono">{totalCount}</span> alerts)
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setPage((p) => Math.max(p - 1, 1))}
              disabled={page <= 1}
              className="p-1.5 rounded-lg bg-slate-950 border border-slate-800 hover:bg-slate-800 disabled:opacity-40 transition-colors"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <span className="font-mono font-medium px-2 text-white">
              {page} / {totalPages}
            </span>
            <button
              onClick={() => setPage((p) => Math.min(p + 1, totalPages))}
              disabled={page >= totalPages}
              className="p-1.5 rounded-lg bg-slate-950 border border-slate-800 hover:bg-slate-800 disabled:opacity-40 transition-colors"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>

      {/* Alert Dossier Modal */}
      <Modal
        isOpen={selectedAlert !== null}
        onClose={() => setSelectedAlert(null)}
        title={`Surveillance Alert #${selectedAlert?.alert_id}`}
        subtitle="Rule explanation and contextual transaction metadata"
        maxWidth="lg"
      >
        {selectedAlert && (
          <div className="space-y-4 text-xs">
            {escalateSuccess && (
              <div className="p-3 rounded-lg bg-emerald-500/15 border border-emerald-500/30 text-emerald-400 flex items-center gap-2">
                <CheckCircle2 className="w-4 h-4 shrink-0" />
                <span>{escalateSuccess}</span>
              </div>
            )}

            {escalateError && (
              <div className="p-3 rounded-lg bg-rose-500/15 border border-rose-500/30 text-rose-400">
                {escalateError}
              </div>
            )}

            <div className="p-4 rounded-xl bg-slate-950 border border-slate-800 space-y-3">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-slate-400 uppercase font-mono text-[10px]">Triggered Rule</p>
                  <p className="text-sm font-semibold text-white mt-0.5">
                    {selectedAlert.rule_triggered}
                  </p>
                </div>
                <SeverityBadge severity={selectedAlert.severity} />
              </div>

              <div className="grid grid-cols-2 gap-3 pt-2 border-t border-slate-900">
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Transaction Amount</p>
                  <p className="text-lg font-bold font-mono text-cyan-400">
                    {selectedAlert.amount ? formatINR(selectedAlert.amount) : 'N/A'}
                  </p>
                </div>
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Alert Status</p>
                  <div className="mt-1">
                    <StatusBadge status={selectedAlert.status} />
                  </div>
                </div>
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Customer Name</p>
                  <p className="text-slate-200 font-medium">{selectedAlert.customer_name || 'N/A'}</p>
                </div>
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Account Number</p>
                  <p className="text-slate-200 font-mono">{selectedAlert.account_number || 'N/A'}</p>
                </div>
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Transaction ID</p>
                  <p className="text-slate-200 font-mono">#{selectedAlert.transaction_id}</p>
                </div>
                <div>
                  <p className="text-slate-400 font-mono text-[10px] uppercase">Detection Time</p>
                  <p className="text-slate-200 font-mono">{selectedAlert.alert_date}</p>
                </div>
              </div>
            </div>

            {/* Investigation linkage */}
            <div className="p-4 rounded-xl bg-slate-950/60 border border-slate-800 flex items-center justify-between">
              <div>
                <p className="text-slate-400 text-[10px] uppercase font-mono">Investigation Docket</p>
                {selectedAlert.has_investigation ? (
                  <p className="text-emerald-400 font-medium mt-0.5 flex items-center gap-1.5">
                    <CheckCircle2 className="w-3.5 h-3.5" />
                    <span>Case Docket #{selectedAlert.investigation_id} Assigned</span>
                  </p>
                ) : (
                  <p className="text-amber-400 font-medium mt-0.5 flex items-center gap-1.5">
                    <AlertTriangle className="w-3.5 h-3.5" />
                    <span>No active investigation docket yet</span>
                  </p>
                )}
              </div>

              {!selectedAlert.has_investigation && (
                <button
                  onClick={() => handleEscalateToInvestigation(selectedAlert)}
                  disabled={isEscalating}
                  className="px-3.5 py-2 rounded-xl bg-cyan-500 hover:bg-cyan-400 text-slate-950 font-bold text-xs flex items-center gap-1.5 transition-all"
                >
                  <Briefcase className="w-3.5 h-3.5" />
                  <span>{isEscalating ? 'Escalating...' : 'Open Case Docket'}</span>
                </button>
              )}
            </div>
          </div>
        )}
      </Modal>
    </div>
  );
};
